/**
 * Which translation namespaces each route needs in the browser.
 *
 * `NextIntlClientProvider` serialises its `messages` into the RSC payload, so
 * every namespace listed here is downloaded, parsed and kept in memory on
 * every page — including the ones that route never renders. The storefront
 * shipped ~81 KiB of JSON to all 60+ routes because the namespace list was a
 * single global constant.
 *
 * The list is resolved per request from the request path instead. The base set
 * covers the shell (header, footer, cart drawer, command palette, chat
 * widget); everything else is added only by the routes that render it.
 */

