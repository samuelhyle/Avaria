/**
 * Namespaces whose browser copy is smaller than the whole namespace.
 *
 * `research`, `experience` and `store` are read by both server and client
 * components. A client component only ever touches a small part of them, but
 * the namespace was serialised into every page in full. The allowlist is
 * generated by `scripts/i18n-client-slice.mjs`.
 */
const SLICED_NAMESPACES = ["research", "experience", "store"] as const

/**
 * Resolve the namespace set for a request path.
 *
 * `pathname` is locale-prefixed (`/fi/shop`), so the locale segment is
 * stripped before the prefixes are matched.
 */
export function clientNamespacesFor(pathname: string): string[] {
  const segments = pathname.split("/").filter(Boolean)
  const route = segments.length > 1 ? `/${segments.slice(1).join("/")}` : "/"
  const names = new Set<string>(BASE)
  for (const { prefix, namespaces } of ROUTE_NAMESPACES) {
    if (route === prefix || route.startsWith(prefix)) {
      for (const namespace of namespaces) names.add(namespace)
    }
  }
  return [...names]
}
